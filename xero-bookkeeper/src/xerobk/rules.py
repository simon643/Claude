def learn_rules(
    history: list[tuple[BankLine, str]],
    min_occurrences: int = 3,
    priority: int = 500,
) -> list[Rule]:
    """Infer rules from previously coded lines.

    ``history`` is a list of ``(line, account_code)`` pairs. A rule is proposed
    only when a distinctive token from the description was coded to the *same*
    account at least ``min_occurrences`` times and was never coded to a
    different one. Requiring unanimity keeps a merchant that legitimately
    splits across two accounts from producing a confidently wrong rule.
    """
    token_accounts: dict[str, dict[str, int]] = {}
    for line, account_code in history:
        if not account_code:
            continue
        for token in _tokens(line.description):
            token_accounts.setdefault(token, {}).setdefault(account_code, 0)
            token_accounts[token][account_code] += 1

    learned: list[Rule] = []
    for token, accounts in token_accounts.items():
        if len(accounts) != 1:
            continue  # ambiguous: the same token maps to more than one account
        account_code, count = next(iter(accounts.items()))
        if count < min_occurrences:
            continue
        learned.append(
            Rule(
                name=f"Learned: {token} -> {account_code}",
                account_code=account_code,
                contains=(token,),
                priority=priority,
                source="learned",
            )
        )
    learned.sort(key=lambda r: (-len(r.contains[0]), r.name))
    return learned


_STOPWORDS = frozenset(
    ["the", "and", "for", "from", "with", "pay", "payment", "payments", "transfer", "tfr", "direct", "debit", "credit", "eftpos", "visa", "mastercard", "card", "purchase", "au", "aus", "australia", "pty", "ltd", "limited", "inc", "co", "bpay", "osko", "payid", "ref", "receipt", "invoice", "inv", "date", "value", "id", "no", "number", "txn", "transaction", "withdrawal", "deposit"]
)


def _tokens(description: str) -> list[str]:
    """Distinctive lowercase words from a bank narrative.

    Bank descriptions are full of noise — card numbers, dates, terminal ids,
    "EFTPOS", "VISA PURCHASE". Anything numeric, too short, or on the stopword
    list is dropped, leaving the merchant name that actually identifies the
    transaction.
    """
    words = re.findall(r"[a-zA-Z][a-zA-Z'&-]{2,}", description.lower())
    return [w for w in words if w not in _STOPWORDS and len(w) >= 4]
